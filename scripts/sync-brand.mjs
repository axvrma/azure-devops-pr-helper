// Regenerate extension branding from the website's original vector mark.
// Only regeneration needs the website's Sharp dev dependency; extension builds use checked-in assets.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const logo = await readFile(new URL('apps/website/public/prism-logo.svg', root), 'utf8');
const paths = logo.slice(logo.indexOf('>') + 1, logo.lastIndexOf('</svg>')).trim();
if (!paths.startsWith('<path') || /<(?:script|image|foreignObject)\b|\bon\w+=/i.test(logo)) { throw new Error('Expected the trusted, path-only Prism SVG.'); }
const themedPaths = paths.replaceAll('stroke="#e7defe"', 'stroke="currentColor"');
const generated = `// Generated by scripts/sync-brand.mjs from apps/website/public/prism-logo.svg.\n// Static vector markup only; never interpolate repository or user data here.\nexport const PRISM_MARK_PATHS = ${JSON.stringify(themedPaths)};\n`;
const monochrome = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 32 32" fill="none">${paths.replace(/stroke="[^"]+"/g, 'stroke="#ffffff"')}</svg>\n`;
const outputs = [['images/prism.svg', logo], ['images/prism-activity.svg', monochrome], ['src/branding/mark.ts', generated]];
if (process.argv.includes('--check')) {
 for (const [name, content] of outputs) {
  if (await readFile(new URL(name, root), 'utf8') !== content) { throw new Error(`${name} is stale. Run npm run brand:sync.`); }
 }
 console.log('Extension vector assets match the website Prism mark.');
} else {
 const requireWebsite = createRequire(new URL('apps/website/package.json', root));
 const sharp = requireWebsite('sharp');
 for (const [name, content] of outputs) { await mkdir(new URL(name.slice(0, name.lastIndexOf('/')) + '/', root), { recursive: true }); await writeFile(new URL(name, root), content); }
 for (const [name, size] of [['images/icon.png', 256], ['images/icon-256.png', 256], ['images/icon-128.png', 128], ['resources/icon.png', 256]]) {
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 256 256"><rect width="256" height="256" rx="48" fill="#111119"/><g transform="translate(32 32) scale(6)" fill="none">${paths}</g></svg>`;
  await sharp(Buffer.from(icon)).png().toFile(fileURLToPath(new URL(name, root)));
 }
 console.log('Generated Prism SVG, monochrome Activity Bar icon, inline mark and 128/256 px extension icons.');
}
